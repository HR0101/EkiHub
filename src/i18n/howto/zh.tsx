/** 使用指南（简体中文）。结构与 ja.tsx 一致。 */
export function HowToZh() {
  return (
    <>
      <h2>基本用法</h2>
      <p>
        EkiHub 会根据每个人出发的车站，找出大家都方便集合的「中心车站」。
      </p>

      <h3>1. 输入车站</h3>
      <p>
        在左侧的「输入最近的车站」面板中输入参加者的车站。
        汉字、假名、罗马字都可以搜索（输入「しんじゅく」或「shinjuku」都能找到新宿）。
        <br />
        点击「＋ 添加车站」可增加输入框。若同一车站有多人出发，请在右侧填写人数；
        人数会作为重心与平均所需时间的权重。
      </p>

      <h3>2. 设定候选范围</h3>
      <p>请按用途切换搜索模式。</p>
      <ul>
        <li>
          <strong>仅限主要车站：</strong>
          新宿、涩谷、东京等换乘方便、周边店铺众多的大型车站（适合聚餐与游玩）。
        </li>
        <li>
          <strong>不限规模：</strong>
          单纯寻找移动时间最短的车站（也包含小型车站）。
        </li>
      </ul>

      <h3>3. 调整优先事项</h3>
      <p>可使用滑杆调整以下平衡。</p>
      <ul>
        <li>
          <strong>重视就近：</strong>
          选择全员合计移动时间最短的车站（整体效率优先）。
        </li>
        <li>
          <strong>重视公平：</strong>
          选择移动时间「离散程度」最小的车站，避免某个人特别远（平等优先）。
        </li>
        <li>
          <strong>票价的重视程度：</strong>
          优先选择平均交通费较低的车站。
        </li>
      </ul>

      <h3>4. 搜索</h3>
      <p>
        点击「搜索中心车站」，右侧会显示推荐结果、各车站的所需时间以及地图上的位置关系。
        <br />
        从候选车站排名中选择其他车站，即可切换为以该车站为准的所需时间。
      </p>

      <h3>5. 分享</h3>
      <p>
        点击结果卡片的「复制链接」，即可将当前条件转为链接。
        对方打开后会以相同条件自动搜索，可直接用于约定集合地点。
        也可以通过二维码分享到手机。
      </p>
    </>
  );
}
